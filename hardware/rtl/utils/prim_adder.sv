/*============================================================================//
region MODULE DEFINITION
//============================================================================*/
module prim_adder
#(
    parameter int unsigned DW = 32
) (
    /*=======================### COMMON SIGNALS ###===========================*/
    input  logic [DW - 1: 0]    a,
    input  logic [DW - 1: 0]    b,
    input  logic                cin,    // carry in
    /*======================### OUT DATA SIGNALS ###==========================*/
    output logic [DW - 1: 0]    sum,
    output logic                cout    // carry out
    //========================================================================//
);

/*============================================================================//
region LOGIC
//============================================================================*/

logic [DW - 1: 0] lcin;
logic [DW - 1: 0] ccin;

/*============================================================================//
region OUT
//============================================================================*/

assign cout = lcin[$left(lcin)]; // get msb

/*============================================================================//
region INSTANCES
//============================================================================*/

for (genvar i = 0; i < DW; i++) begin: gen_full_adders
    if (i == 0) begin: gen_fisrt_cin
        assign ccin[i] = cin;
    end
    else begin: gen_other_cin
        assign ccin[i] = lcin[i - 1];
    end

    //                    *** FULL ADDER ***                     //
    // NOTE: full adder for i-bit
    full_adder full_adder_u (
        //================### COMMON SIGNALS ###=================//
        .a    (a[i]   ), // <-
        .b    (b[i]   ), // <-
        .cin  (ccin[i]), // <-
        //===============### OUT DATA SIGNALS ###================//
        .sum  (sum[i] ), // ->
        .cout (lcin[i])  // ->
        //=======================================================//
    );
    // ///////////////////////////////////////////////////////// //

end

//============================================================================*/
endmodule
