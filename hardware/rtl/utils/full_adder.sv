/*============================================================================//
region MODULE DEFINITION
//============================================================================*/
module full_adder
#() (
    /*=======================### COMMON SIGNALS ###===========================*/
    input  logic    a,
    input  logic    b,
    input  logic    cin,    // carry in
    /*======================### OUT DATA SIGNALS ###==========================*/
    output logic    sum,
    output logic    cout    // carry out
    //========================================================================//
);

/*============================================================================//
region OUT
//============================================================================*/

assign sum  = a ^ b ^ cin;
assign cout = (a & b) | (b & cin) | (a & cin);

//============================================================================*/
endmodule
