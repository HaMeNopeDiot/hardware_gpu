module prim_bit
(
    /*==========================### COMMON SIGNALS ###==========================*/
    input  logic                         clk,
    input  logic                         rst_n,
    input  logic                         we,
    input  logic                         wbit,
    output logic                         rbit
    /*==========================================================================*/
);
//==============================================================================//
// LOGIC
//==============================================================================//

// write
always_ff @(posedge clk or negedge rst_n) begin
    if (~rst_n)
        rbit <= '0;
    else if (we)
        rbit <= wbit;
end

//==============================================================================//
endmodule
