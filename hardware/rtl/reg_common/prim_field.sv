module prim_field
    import register_pkg::*;
#(
    /*==========================### COMMON SIGNALS ###==========================*/
    parameter  int unsigned             FIELD_W = 8
) (
    /*==========================### COMMON SIGNALS ###==========================*/
    input logic                         clk,
    input logic                         rst_n,

    input logic [FIELD_W - 1: 0]        wdata,
    input logic [FIELD_W - 1: 0]        wedata,
    output logic [FIELD_W - 1: 0]       rdata
    /*==========================================================================*/
);
//==============================================================================//
// LOGIC
//==============================================================================//

for (genvar i = 0; i < FIELD_W; i++) begin: g_bits
    prim_bit bit_u (
        /*================### COMMON SIGNALS ###=================*/
        .clk    (clk),                  // <-
        .rst_n  (rst_n),                // <-
        /*================### PACKET SIGNALS ###=================*/
        .we     (wedata[i]),            // <-
        .wbit   (wdata[i]),             // <-
        .rbit   (rdata[i])              // ->
        //=======================================================//
    );
end: g_bits

//==============================================================================//
endmodule
